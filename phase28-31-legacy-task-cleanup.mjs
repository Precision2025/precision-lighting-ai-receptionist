import fs from "node:fs";

/*
 * Joshua Phase 28.31 — legacy open-task cleanup
 *
 * Purpose:
 *   Remove stale Joshua-generated task records that predate the newer
 *   workflow metadata while preserving real manual/callback/documentation work.
 *
 * Expected result:
 *   Open Tasks should reconcile to the actual actionable workflow instead of
 *   carrying legacy duplicates/orphans/generic customer-status tasks.
 */

const PERSISTENT_FILE =
  process.env.CONTROL_DATA_FILE || "/var/data/joshua-control-data.json";

function text(value = "") {
  return String(value ?? "").trim();
}

function lower(value = "") {
  return text(value).toLowerCase();
}

function norm(value = "") {
  return lower(value)
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function isClosed(task = {}) {
  return ["closed", "completed"].includes(norm(task.status));
}

function taskBody(task = {}) {
  return [
    task.title,
    task.notes,
    task.source,
    task.actionLabel,
    task.workflowType,
    task.closedReason
  ]
    .map(lower)
    .filter(Boolean)
    .join(" ");
}

function taskClass(task = {}) {
  const workflow = norm(task.workflowType);
  const body = taskBody(task);

  if (
    workflow === "proposal" ||
    /prepare.*(?:quote|proposal)|submit.*(?:quote|proposal)|proposal follow.?up/.test(body)
  ) return "proposal";

  if (
    workflow === "parts" ||
    /order parts|parts follow.?up|parts on order|prepare return visit/.test(body)
  ) return "parts";

  if (
    workflow === "billing" ||
    /prepare.*invoice|submit.*invoice|billing/.test(body)
  ) return "billing";

  if (workflow === "authorization" || /authorization/.test(body)) {
    return "authorization";
  }

  if (
    workflow === "return_trip" ||
    /schedule return|return trip|return visit/.test(body)
  ) return "return_trip";

  if (
    workflow === "pending_confirmation" ||
    /confirm servicechannel completion|confirm completion/.test(body)
  ) return "pending_confirmation";

  if (
    workflow === "checkout_review" ||
    workflow === "clockshark_servicechannel_mismatch" ||
    /verify stale clockshark|stale clockshark|clockshark.*servicechannel.*mismatch|servicechannel.*clockshark.*mismatch|resolve.*status mismatch|verify technician checkout|review unclear checkout/.test(body)
  ) return "status_verification";

  if (
    workflow === "documentation" ||
    /documentation|completion notes|photos/.test(body)
  ) return "documentation";

  if (
    workflow === "callback" ||
    /callback|return.*call|call.*customer/.test(body)
  ) return "callback";

  return workflow || "general";
}

const PRIMARY_CLASSES = new Set([
  "proposal",
  "parts",
  "billing",
  "authorization",
  "return_trip",
  "pending_confirmation",
  "status_verification"
]);

function isLegacyJoshuaTitle(task = {}) {
  const body = taskBody(task);

  return (
    /prepare\s+(?:and\s+)?submit\s+(?:invoice|quote|proposal)/.test(body) ||
    /order\s+parts(?:\s+and\s+prepare\s+return\s+visit)?/.test(body) ||
    /parts\s+follow.?up/.test(body) ||
    /proposal\s+follow.?up/.test(body) ||
    /obtain\s+(?:customer\s+or\s+servicechannel\s+)?authorization/.test(body) ||
    /schedule\s+return\s+(?:visit|trip)/.test(body) ||
    /confirm\s+(?:servicechannel\s+)?completion/.test(body) ||
    /verify\s+stale\s+clockshark/.test(body) ||
    /resolve\s+clockshark\s+and\s+servicechannel\s+status\s+mismatch/.test(body) ||
    /verify\s+technician\s+checkout/.test(body) ||
    /review\s+unclear\s+checkout/.test(body) ||
    /update\s+customer\s+on\s+current\s+job\s+status/.test(body)
  );
}

function isClearlyGenerated(task = {}) {
  const body = taskBody(task);

  return Boolean(
    task.phase2829AtomicPrimaryTask ||
    task.phase2828DisabledStatusTask ||
    task.phase2825GeneratedTask ||
    task.phase28GeneratedTask ||
    task.autoGenerated ||
    task.generatedByJoshua ||
    task.workflowType ||
    task.actionLabel ||
    /joshua|phase\s*\d+|atomic workflow|workflow authority|reconciler|auto.?generated|automation/.test(body) ||
    isLegacyJoshuaTitle(task)
  );
}

function hasExplicitCustomerContactEvidence(task = {}) {
  const body = taskBody(task);

  return Boolean(
    task.customerRequestedUpdate ||
    task.customerContactRequired ||
    task.callbackRequired ||
    task.callerRequestedFollowup ||
    /customer\s+(?:requested|asked)|caller\s+(?:requested|asked)|callback|call\s+back|return\s+call|contact\s+customer\s+requested/.test(body)
  );
}

function closeTask(task, now, reason, marker = {}) {
  return {
    ...task,
    status: "closed",
    closedAt: task.closedAt || now,
    completedAt: task.completedAt || now,
    updatedAt: now,
    accountabilityStatus: "completed",
    closedReason: reason,
    ...marker
  };
}

function buildAliasMap(workOrders = {}) {
  const map = new Map();

  for (const [key, workOrder] of Object.entries(workOrders || {})) {
    if (!workOrder || typeof workOrder !== "object") continue;

    for (const value of [
      key,
      workOrder.trackingNumber,
      workOrder.tracking,
      workOrder.workOrderNumber,
      workOrder.workOrder,
      workOrder.woNumber,
      workOrder.wo
    ]) {
      const raw = text(value);
      if (!raw) continue;
      map.set(raw, key);
      map.set(norm(raw), key);
    }
  }

  return map;
}

function canonicalKeyForTask(task, aliasMap) {
  const tracking = text(task.trackingNumber);
  if (!tracking) return "";
  return aliasMap.get(tracking) || aliasMap.get(norm(tracking)) || "";
}

function repairPersistedTasks() {
  if (!fs.existsSync(PERSISTENT_FILE)) {
    return {
      normalized: 0,
      genericCustomerUpdatesClosed: 0,
      orphanedClosed: 0,
      aliasesNormalized: 0,
      duplicatesClosed: 0
    };
  }

  try {
    const data = JSON.parse(fs.readFileSync(PERSISTENT_FILE, "utf8"));
    data.tasks = Array.isArray(data.tasks) ? data.tasks : [];
    data.workOrders =
      data.workOrders && typeof data.workOrders === "object"
        ? data.workOrders
        : {};

    const now = new Date().toISOString();
    const aliasMap = buildAliasMap(data.workOrders);

    let normalized = 0;
    let genericCustomerUpdatesClosed = 0;
    let orphanedClosed = 0;
    let aliasesNormalized = 0;
    let duplicatesClosed = 0;

    data.tasks = data.tasks.map(task => {
      if (!task || typeof task !== "object") return task;

      const status = norm(task.status || "open");
      if (status === "closed") return task;

      if (status === "completed") {
        normalized += 1;
        return closeTask(
          task,
          now,
          "Phase 28.31 normalized completed history to closed.",
          { phase2831CompletedNormalized: true }
        );
      }

      const body = taskBody(task);
      const genericCustomerUpdate =
        /update\s+customer\s+on\s+current\s+job\s+status/.test(body);

      if (
        genericCustomerUpdate &&
        !hasExplicitCustomerContactEvidence(task)
      ) {
        genericCustomerUpdatesClosed += 1;
        return closeTask(
          task,
          now,
          "Phase 28.31 retired obsolete generic customer-status follow-up. Explicit customer-requested callbacks remain protected.",
          { phase2831GenericCustomerUpdateClosed: true }
        );
      }

      const klass = taskClass(task);

      if (!isClearlyGenerated(task) || !PRIMARY_CLASSES.has(klass)) {
        return task;
      }

      const canonical = canonicalKeyForTask(task, aliasMap);

      if (!canonical) {
        orphanedClosed += 1;
        return closeTask(
          task,
          now,
          "Phase 28.31 retired orphaned Joshua-generated workflow task; no canonical work order resolves its tracking identity.",
          { phase2831OrphanGeneratedClosed: true }
        );
      }

      if (text(task.trackingNumber) !== text(canonical)) {
        aliasesNormalized += 1;
        return {
          ...task,
          trackingNumber: canonical,
          updatedAt: now,
          phase2831TrackingAliasNormalized: true
        };
      }

      return task;
    });

    // After alias normalization, keep one generated primary task per
    // canonical tracking/class pair. Phase 28.29 will then enforce the
    // authoritative workflow and regenerate a missing task if necessary.
    const seen = new Set();

    data.tasks = data.tasks.map(task => {
      if (!task || typeof task !== "object" || isClosed(task)) return task;

      const klass = taskClass(task);
      if (!PRIMARY_CLASSES.has(klass) || !isClearlyGenerated(task)) return task;

      const tracking = text(task.trackingNumber);
      if (!tracking) return task;

      const key = `${tracking}|${klass}`;

      if (!seen.has(key)) {
        seen.add(key);
        return task;
      }

      duplicatesClosed += 1;
      return closeTask(
        task,
        now,
        `Phase 28.31 retired duplicate ${klass} task for the same canonical work order.`,
        { phase2831DuplicateGeneratedClosed: true }
      );
    });

    if (
      normalized ||
      genericCustomerUpdatesClosed ||
      orphanedClosed ||
      aliasesNormalized ||
      duplicatesClosed
    ) {
      data.phase2831 = {
        ...(data.phase2831 || {}),
        completedNormalized:
          Number(data.phase2831?.completedNormalized || 0) + normalized,
        genericCustomerUpdatesClosed:
          Number(data.phase2831?.genericCustomerUpdatesClosed || 0) +
          genericCustomerUpdatesClosed,
        orphanedGeneratedClosed:
          Number(data.phase2831?.orphanedGeneratedClosed || 0) +
          orphanedClosed,
        trackingAliasesNormalized:
          Number(data.phase2831?.trackingAliasesNormalized || 0) +
          aliasesNormalized,
        duplicateGeneratedClosed:
          Number(data.phase2831?.duplicateGeneratedClosed || 0) +
          duplicatesClosed,
        lastRepairAt: now
      };

      data.updatedAt = now;
      fs.writeFileSync(PERSISTENT_FILE, JSON.stringify(data, null, 2));
    }

    return {
      normalized,
      genericCustomerUpdatesClosed,
      orphanedClosed,
      aliasesNormalized,
      duplicatesClosed
    };
  } catch (error) {
    console.warn(
      "Joshua Phase 28.31 persisted legacy-task cleanup warning:",
      error.message
    );

    return {
      normalized: 0,
      genericCustomerUpdatesClosed: 0,
      orphanedClosed: 0,
      aliasesNormalized: 0,
      duplicatesClosed: 0
    };
  }
}

function patchPhase2829LegacyHandling() {
  const phasePath = new URL(
    "./phase28-29-atomic-workflow-snapshot.mjs",
    import.meta.url
  );

  if (!fs.existsSync(phasePath)) return false;

  let source = fs.readFileSync(phasePath, "utf8");
  let changed = false;

  if (!source.includes("JOSHUA_PHASE28_31_GENERIC_CUSTOMER_UPDATE")) {
    const anchor =
      '    const klass = taskClass(task);\n\n    /* Explicit separate/manual work stays separate. */';

    const replacement =
      '    const klass = taskClass(task);\n' +
      '    // JOSHUA_PHASE28_31_GENERIC_CUSTOMER_UPDATE\n' +
      '    const phase2831Body = lower([task.title, task.notes, task.source, task.actionLabel, task.workflowType].filter(Boolean).join(" "));\n' +
      '    const phase2831GenericCustomerUpdate = /update\\\\s+customer\\\\s+on\\\\s+current\\\\s+job\\\\s+status/.test(phase2831Body);\n' +
      '    const phase2831ExplicitCustomerContact = Boolean(\n' +
      '      task.customerRequestedUpdate || task.customerContactRequired || task.callbackRequired || task.callerRequestedFollowup ||\n' +
      '      /customer\\\\s+(?:requested|asked)|caller\\\\s+(?:requested|asked)|callback|call\\\\s+back|return\\\\s+call/.test(phase2831Body)\n' +
      '    );\n' +
      '    if (phase2831GenericCustomerUpdate && !phase2831ExplicitCustomerContact) {\n' +
      '      return closeTask(task, now, "Obsolete generic customer-status follow-up retired by Phase 28.31.");\n' +
      '    }\n\n' +
      '    /* Explicit separate/manual work stays separate. */';

    if (source.includes(anchor)) {
      source = source.replace(anchor, replacement);
      changed = true;
    } else {
      console.warn(
        "Joshua Phase 28.31: generic-customer-update anchor was not found."
      );
    }
  }

  if (!source.includes("JOSHUA_PHASE28_31_LEGACY_ORPHAN")) {
    const oldLine = "    if (!workOrder) return task;";

    const replacement = `    if (!workOrder) {
      // JOSHUA_PHASE28_31_LEGACY_ORPHAN
      const legacyBody = lower(
        [task.title, task.notes, task.source, task.actionLabel, task.workflowType]
          .filter(Boolean)
          .join(" ")
      );

      const legacyGenerated = Boolean(
        task.phase2829AtomicPrimaryTask ||
        task.workflowType ||
        task.actionLabel ||
        /joshua|phase\\s*\\d+|atomic workflow|workflow authority|reconciler|auto.?generated|automation/.test(legacyBody) ||
        /prepare\\s+(?:and\\s+)?submit\\s+(?:invoice|quote|proposal)|order\\s+parts|parts\\s+follow.?up|proposal\\s+follow.?up|obtain\\s+(?:customer\\s+or\\s+servicechannel\\s+)?authorization|schedule\\s+return\\s+(?:visit|trip)|confirm\\s+(?:servicechannel\\s+)?completion|verify\\s+stale\\s+clockshark|resolve\\s+clockshark\\s+and\\s+servicechannel\\s+status\\s+mismatch|verify\\s+technician\\s+checkout|review\\s+unclear\\s+checkout/.test(legacyBody)
      );

      if (primaryClasses.has(klass) && legacyGenerated) {
        return closeTask(
          task,
          now,
          "Orphaned legacy Joshua workflow task retired; no canonical work order resolves this tracking identity."
        );
      }

      return task;
    }`;

    if (source.includes(oldLine)) {
      source = source.replace(oldLine, replacement);
      changed = true;
    } else {
      console.warn(
        "Joshua Phase 28.31: Phase 28.29 orphan-task anchor was not found."
      );
    }
  }

  if (changed) {
    fs.writeFileSync(phasePath, source);
    console.log(
      "Joshua Phase 28.31 hardened Phase 28.29 legacy-task cleanup."
    );
  }

  return changed;
}

const repaired = repairPersistedTasks();
const hardened = patchPhase2829LegacyHandling();

console.log(
  `Joshua Phase 28.31 preflight: normalized ${repaired.normalized} completed task(s), ` +
  `closed ${repaired.genericCustomerUpdatesClosed} generic customer-update task(s), ` +
  `${repaired.orphanedClosed} orphan generated task(s), ` +
  `${repaired.duplicatesClosed} duplicate generated task(s), ` +
  `normalized ${repaired.aliasesNormalized} tracking alias(es); ` +
  `future-write hardening ${hardened ? "installed" : "already present/not needed"}.`
);

await import("./phase28-30-task-count-and-pp-repair.mjs");
