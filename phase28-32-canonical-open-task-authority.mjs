import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/* Joshua Phase 28.32 — Canonical Open Task Authority
 * Makes stale-task cleanup persistent at every control-data write.
 */

const FILE = process.env.CONTROL_DATA_FILE || "/var/data/joshua-control-data.json";
const BASE = "joshua-control-data.json";
const nativeWrite = fs.writeFileSync.bind(fs);
const nativeRead = fs.readFileSync.bind(fs);
const nativeExists = fs.existsSync.bind(fs);

const text = v => String(v ?? "").trim();
const lower = v => text(v).toLowerCase();
const norm = v => lower(v).replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");
const closed = t => ["closed", "completed"].includes(norm(t?.status));

function controlPath(file) {
  let raw = "";
  try {
    raw = file instanceof URL && file.protocol === "file:" ? fileURLToPath(file) : String(file ?? "");
  } catch { raw = String(file ?? ""); }
  const b = path.basename(raw);
  return b === BASE || b.startsWith(BASE + ".tmp-") || b.startsWith(BASE + ".phase");
}

function body(t = {}) {
  return [t.title, t.notes, t.source, t.actionLabel, t.workflowType, t.closedReason]
    .map(lower).filter(Boolean).join(" ");
}

function taskClass(t = {}) {
  const w = norm(t.workflowType), b = body(t);
  if (w === "proposal" || /prepare.*(?:quote|proposal)|submit.*(?:quote|proposal)|proposal follow.?up/.test(b)) return "proposal";
  if (w === "parts" || /order parts|parts follow.?up|parts on order|prepare return visit/.test(b)) return "parts";
  if (w === "billing" || /prepare.*invoice|submit.*invoice|billing/.test(b)) return "billing";
  if (w === "authorization" || /authorization/.test(b)) return "authorization";
  if (w === "return_trip" || /schedule return|return trip|return visit/.test(b)) return "return_trip";
  if (w === "pending_confirmation" || /confirm servicechannel completion|confirm completion/.test(b)) return "pending_confirmation";
  if (w === "checkout_review" || w === "clockshark_servicechannel_mismatch" || /verify stale clockshark|clockshark.*servicechannel.*mismatch|servicechannel.*clockshark.*mismatch|resolve.*status mismatch|verify technician checkout|review unclear checkout/.test(b)) return "status_verification";
  if (w === "documentation" || /documentation|completion notes|photos/.test(b)) return "documentation";
  if (w === "callback" || /callback|return.*call|call.*customer/.test(b)) return "callback";
  return w || "general";
}

const primary = new Set(["proposal","parts","billing","authorization","return_trip","pending_confirmation","status_verification"]);

function generatedTitle(t = {}) {
  const b = body(t);
  return /update\s+customer\s+on\s+current\s+job\s+status|prepare\s+(?:and\s+)?submit\s+(?:invoice|quote|proposal)|order\s+parts|parts\s+follow.?up|proposal\s+follow.?up|obtain\s+(?:customer\s+or\s+servicechannel\s+)?authorization|schedule\s+return\s+(?:visit|trip)|confirm\s+(?:servicechannel\s+)?completion|verify\s+stale\s+clockshark|resolve\s+clockshark\s+and\s+servicechannel\s+status\s+mismatch|verify\s+technician\s+checkout|review\s+unclear\s+checkout/.test(b);
}

function generated(t = {}) {
  const b = body(t);
  return Boolean(t.phase2829AtomicPrimaryTask || t.phase2828DisabledStatusTask || t.phase2825GeneratedTask || t.phase28GeneratedTask || t.autoGenerated || t.generatedByJoshua || t.workflowType || t.actionLabel || /joshua|phase\s*\d+|atomic workflow|workflow authority|reconciler|auto.?generated|automation/.test(b) || generatedTitle(t));
}

function explicitContact(t = {}) {
  const b = body(t);
  return Boolean(t.customerRequestedUpdate || t.customerContactRequired || t.callbackRequired || t.callerRequestedFollowup || /customer\s+(?:requested|asked)|caller\s+(?:requested|asked)|callback|call\s+back|return\s+call/.test(b));
}

function manual(t = {}) {
  return Boolean(t.manual === true || t.userCreated === true || t.createdByUser === true || /manual|control panel user|created by user/.test(lower(t.source)));
}

function closeTask(t, now, reason) {
  return { ...t, status: "closed", closedAt: t.closedAt || now, completedAt: t.completedAt || now, updatedAt: now, accountabilityStatus: "completed", closedReason: reason, phase2832CanonicalClosed: true };
}

function mapState(v = "") {
  const s = norm(v);
  if (!s) return "";
  if (["parts","parts_needed","parts_on_order","waiting_for_parts","waiting_on_parts"].includes(s)) return "parts_needed";
  if (["quote","proposal","estimate","pending_proposal","proposal_needed","quote_needed"].includes(s)) return "pending_proposal";
  if (["bill","billing","ready_to_bill","ready_for_billing"].includes(s)) return "ready_to_bill";
  if (["awaiting_authorization","authorization_needed","pending_authorization"].includes(s) || (/authorization/.test(s) && !/authorized|approved/.test(s))) return "awaiting_authorization";
  if (["schedule","scheduled_return","need_to_schedule"].includes(s) || /return.*visit|return.*trip|reschedule/.test(s)) return "need_to_schedule";
  if (["pending_confirmation","completed_pending_confirmation"].includes(s) || /completed.*pending.*confirmation/.test(s)) return "pending_confirmation";
  if (["completed","complete","completed_confirmed","closed","paid","submitted","invoiced","invoice_submitted"].includes(s)) return "terminal";
  return s;
}

function authoritativeState(w = {}) {
  if ([w.paymentStatus, w.invoiceStatus].some(v => mapState(v) === "terminal")) return "terminal";
  for (const v of [w.sheetStatus,w.jobSheetStatus,w.jobsSheetStatus,w.officeStatus,w.workflowStatus]) {
    const s = mapState(v);
    if (["parts_needed","pending_proposal","ready_to_bill","awaiting_authorization","need_to_schedule"].includes(s)) return s;
  }
  const current = mapState(w.joshuaStatus || w.state || w.status);
  if (current) return current;
  const sc = [w.serviceChannelPrimaryStatus,w.serviceChannelExtendedStatus,w.primaryStatus,w.extendedStatus,w.statusDescription].map(lower).join(" ");
  if (/parts?\s*(?:on\s*order|ordered|needed|required)|waiting\s*(?:on|for)\s*parts?/.test(sc)) return "parts_needed";
  if (/proposal\s*(?:required|needed|pending)|quote\s*(?:required|needed|pending)/.test(sc)) return "pending_proposal";
  if (/authorization\s*(?:required|needed|pending)|awaiting\s*authorization/.test(sc)) return "awaiting_authorization";
  if (/completed.*pending.*confirmation/.test(sc)) return "pending_confirmation";
  if (/completed.*confirmed/.test(sc)) return "terminal";
  return "";
}

function expectedClass(state) {
  return ({pending_proposal:"proposal",parts_needed:"parts",ready_to_bill:"billing",awaiting_authorization:"authorization",need_to_schedule:"return_trip"})[state] || "";
}

function aliases(workOrders = {}) {
  const map = new Map();
  for (const [key, w] of Object.entries(workOrders)) {
    if (!w || typeof w !== "object") continue;
    for (const v of [key,w.trackingNumber,w.tracking,w.workOrderNumber,w.workOrder,w.woNumber,w.wo]) {
      const raw = text(v); if (!raw) continue; map.set(raw,key); map.set(norm(raw),key);
    }
  }
  return map;
}

function sanitize(data = {}) {
  data.tasks = Array.isArray(data.tasks) ? data.tasks : [];
  data.workOrders = data.workOrders && typeof data.workOrders === "object" ? data.workOrders : {};
  const now = new Date().toISOString(), index = aliases(data.workOrders), seen = new Set();

  data.tasks = data.tasks.map(t => {
    if (!t || typeof t !== "object") return t;
    const s = norm(t.status || "open");
    if (s === "closed") return t;
    if (s === "completed") return closeTask(t, now, "Phase 28.32 normalized completed task history.");

    const b = body(t), klass = taskClass(t);
    if (/update\s+customer\s+on\s+current\s+job\s+status/.test(b) && !explicitContact(t)) return closeTask(t, now, "Phase 28.32 retired obsolete generic customer-status follow-up.");
    if (manual(t) || klass === "documentation" || (klass === "callback" && explicitContact(t))) return t;
    if (!generated(t)) return t;

    const raw = text(t.trackingNumber), canonical = index.get(raw) || index.get(norm(raw)) || "";
    if (!canonical) return closeTask(t, now, "Phase 28.32 retired orphaned generated task with no canonical work order.");

    const state = authoritativeState(data.workOrders[canonical]), expected = expectedClass(state);
    if (!expected) {
      if (primary.has(klass) || generatedTitle(t)) return closeTask(t, now, `Phase 28.32 retired generated task because ${state || "the work order"} has no active primary workflow.`);
      return t;
    }
    if (klass !== expected) return closeTask(t, now, `Phase 28.32 retired generated ${klass} task; canonical workflow is ${state}.`);

    const key = `${canonical}|${expected}`;
    if (seen.has(key)) return closeTask(t, now, `Phase 28.32 retired duplicate ${expected} task.`);
    seen.add(key);
    return raw === canonical ? t : { ...t, trackingNumber: canonical, updatedAt: now, phase2832TrackingAliasNormalized: true };
  });

  data.phase2832 = { ...(data.phase2832 || {}), lastSanitizedAt: now };
  return data;
}

function parsePayload(payload, encoding) {
  try {
    if (Buffer.isBuffer(payload)) return JSON.parse(payload.toString(typeof encoding === "string" ? encoding : "utf8"));
    if (typeof payload === "string") return JSON.parse(payload);
  } catch {}
  return null;
}

fs.writeFileSync = function(file, payload, options) {
  if (controlPath(file)) {
    const encoding = typeof options === "string" ? options : (options?.encoding || "utf8");
    const parsed = parsePayload(payload, encoding);
    if (parsed) {
      const serialized = JSON.stringify(sanitize(parsed), null, 2);
      payload = Buffer.isBuffer(payload) ? Buffer.from(serialized, encoding) : serialized;
    }
  }
  return nativeWrite(file, payload, options);
};

try {
  if (nativeExists(FILE)) {
    const data = JSON.parse(nativeRead(FILE, "utf8"));
    const before = Array.isArray(data.tasks) ? data.tasks.filter(t => t && !closed(t)).length : 0;
    const cleaned = sanitize(data);
    const after = cleaned.tasks.filter(t => t && !closed(t)).length;
    nativeWrite(FILE, JSON.stringify(cleaned, null, 2));
    console.log(`Joshua Phase 28.32 canonical task authority: open tasks ${before} -> ${after}.`);
  }
} catch (error) {
  console.warn("Joshua Phase 28.32 startup cleanup warning:", error.message);
}

await import("./phase28-31-legacy-task-cleanup.mjs");
